#!/usr/bin/env python3
"""mkassets.py - build the OS assets (run from the os/ folder).

  palette.bin     64-colour VGA palette, 6-bit RGB, from shooter/video.inc
  consts.inc      palette index of the UI colours (C_BLACK, C_BG, ...)
  font8x16.bin    256 glyphs, 8x16, from the kbd console font
  hello.txt       text for HELLO.TXT
  music.spk       melody for MUSIC.SPK (PIT divisor, ticks) pairs
  pic.bin         PIC.IMG, 320x200 palette indices (from a Downloads photo)
  clip.bin        CLIP.VID, 80x50 frames (from a Downloads video)
"""
import gzip
import os
import subprocess
import tempfile

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SHOOTER = os.path.join(HERE, "..", "shooter")
ASSETS = os.path.join(HERE, "..", "assets")
PIC_SRC = os.path.join(ASSETS, "pic_source.jpeg")
VIDEO_SRC = os.path.join(ASSETS, "clip_source.mp4")
FONT_SRC = os.path.join(ASSETS, "default8x16.psfu.gz")
VIDEO_FRAMES = 14
ASPECT = 1.6                        # 320x200 and 80x50 are both 16:10

UI_COLOURS = {                      # name -> RGB, mapped to nearest palette entry
    "C_BLACK":  (0, 0, 0),
    "C_WHITE":  (255, 255, 255),
    "C_GRAY":   (160, 160, 160),
    "C_BLUE":   (30, 60, 170),
    "C_BG":     (20, 22, 36),
    "C_PANEL":  (50, 54, 80),
    "C_ACCENT": (240, 190, 40),
    "C_WINBG":  (24, 137, 32),          # green window like the slide
}


def load_palette():
    txt = open(os.path.join(SHOOTER, "video.inc")).read()
    part = txt.split("palette_data:")[1].split("; ----")[0]
    nums = []
    for line in part.splitlines():
        line = line.split(";")[0].strip()
        if line.startswith("db"):
            nums += [int(x) for x in line[2:].replace(" ", "").split(",") if x]
    assert len(nums) == 192, len(nums)
    return bytes(nums)


PAL6 = load_palette()
PAL8 = (np.frombuffer(PAL6, np.uint8).reshape(64, 3).astype(np.float32)
        * 255 / 63)


def to_index(rgb):
    """(N,3) uint8 pixels -> (N,) palette indices (nearest colour)."""
    px = rgb.astype(np.float32)
    out = np.empty(len(px), np.uint8)
    for i in range(0, len(px), 4096):
        d = ((px[i:i + 4096, None, :] - PAL8[None]) ** 2).sum(2)
        out[i:i + 4096] = d.argmin(1)
    return out


def nearest(rgb):
    return int(((PAL8 - np.array(rgb, np.float32)) ** 2).sum(1).argmin())


def crop_aspect(im):
    w, h = im.size
    if w / h > ASPECT:
        nw = round(h * ASPECT)
        x0 = (w - nw) // 2
        return im.crop((x0, 0, x0 + nw, h))
    nh = round(w / ASPECT)
    y0 = (h - nh) // 2
    return im.crop((0, y0, w, y0 + nh))


def write(name, data):
    with open(os.path.join(HERE, name), "wb") as f:
        f.write(data)
    print(f"wrote {name} ({len(data)} bytes)")


def make_palette_and_consts():
    write("palette.bin", PAL6)
    lines = ["; AUTO-GENERATED by mkassets.py - UI colour indices"]
    idx = {}
    for name, rgb in UI_COLOURS.items():
        idx[name] = nearest(rgb)
        lines.append(f"%define {name} {idx[name]}")
    lines.append(f"%define C_TEXT {idx['C_WHITE']}")
    with open(os.path.join(HERE, "consts.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote consts.inc:", ", ".join(f"{k}={v}" for k, v in idx.items()))


def make_font():
    data = gzip.open(FONT_SRC).read()
    if data[:2] == b"\x36\x04":                 # PSF1
        charsize, start = data[3], 4
    elif data[:4] == b"\x72\xb5\x4a\x86":       # PSF2
        start = int.from_bytes(data[8:12], "little")
        charsize = int.from_bytes(data[20:24], "little")
    else:
        raise SystemExit("unknown font format")
    assert charsize == 16, charsize
    write("font8x16.bin", data[start:start + 256 * 16])


def make_text():
    text = (
        "HELLO FROM THE OS!\n"
        "\n"
        "This file was read from the disk by the\n"
        "kernel and is shown on the screen here.\n"
        "\n"
        "Files on this disk: HELLO.TXT, PIC.IMG,\n"
        "MUSIC.SPK, CLIP.VID and DUKE.BIN.\n"
        "\n"
        "Press B to go back to the file list.\n"
    )
    write("hello.txt", text.encode("ascii"))


def make_music():
    # Twinkle Twinkle Little Star, one octave (C4). Durations in 10 ms ticks.
    freq = {"C": 262, "D": 294, "E": 330, "F": 349, "G": 392, "A": 440}
    phrases = [
        "C C G G A A G",
        "F F E E D D C",
        "G G F F E E D",
        "G G F F E E D",
        "C C G G A A G",
        "F F E E D D C",
    ]
    out = b""
    for ph in phrases:
        notes = ph.split()
        for i, n in enumerate(notes):
            dur = 80 if i == len(notes) - 1 else 40
            div = round(1193182 / freq[n])
            out += div.to_bytes(2, "little") + dur.to_bytes(2, "little")
    out += b"\x00\x00\x00\x00"                  # end marker (divisor 0)
    write("music.spk", out)


def make_picture():
    im = Image.open(PIC_SRC).convert("RGB")
    im = crop_aspect(im).resize((320, 200), Image.LANCZOS)
    idx = to_index(np.asarray(im).reshape(-1, 3))
    write("pic.bin", idx.tobytes())


def make_video():
    tmp = tempfile.mkdtemp()
    dur = float(subprocess.check_output([
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "csv=p=0", VIDEO_SRC]).strip())
    frames = []
    for i in range(VIDEO_FRAMES):
        t = dur * (i + 0.5) / VIDEO_FRAMES
        png = os.path.join(tmp, f"f{i}.png")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{t:.3f}",
                        "-i", VIDEO_SRC, "-frames:v", "1", png], check=True)
        im = Image.open(png).convert("RGB")
        im = crop_aspect(im).resize((80, 50), Image.LANCZOS)
        frames.append(to_index(np.asarray(im).reshape(-1, 3)).tobytes())
    data = VIDEO_FRAMES.to_bytes(2, "little") + b"\x00\x00" + b"".join(frames)
    write("clip.bin", data)


def make_icons():
    """icons.bin: six 16x16 icons (menu order), one palette index per pixel,
    0xFF = transparent. Drawn with PIL, colours snapped to the palette."""
    from PIL import ImageDraw
    colours = {
        "black": (0, 0, 0), "white": (250, 250, 250), "gray": (150, 150, 150),
        "sky": (120, 180, 240), "yellow": (250, 200, 40),
        "green": (60, 160, 60), "magenta": (200, 60, 200),
        "blue": (30, 90, 200), "red": (220, 50, 50),
    }
    K, W, G = colours["black"], colours["white"], colours["gray"]
    S, Y, GR = colours["sky"], colours["yellow"], colours["green"]
    M, B, R = colours["magenta"], colours["blue"], colours["red"]
    T = (0, 0, 0, 0)

    def canvas():
        return Image.new("RGBA", (16, 16), T)

    icons = []
    # 0 TEXT: a page with lines of text
    im = canvas(); d = ImageDraw.Draw(im)
    d.rectangle((3, 1, 12, 14), fill=W + (255,), outline=K + (255,))
    for y in (4, 6, 8, 10, 12):
        d.line((5, y, 10, y), fill=G + (255,))
    icons.append(im)
    # 1 PIC: sky, sun, two hills
    im = canvas(); d = ImageDraw.Draw(im)
    d.rectangle((1, 2, 14, 13), fill=S + (255,), outline=K + (255,))
    d.ellipse((9, 4, 12, 7), fill=Y + (255,))
    d.polygon([(2, 12), (6, 8), (10, 12)], fill=GR + (255,))
    d.polygon([(7, 12), (11, 9), (13, 12)], fill=GR + (255,))
    icons.append(im)
    # 2 MUSIC: magenta tile with a note
    im = canvas(); d = ImageDraw.Draw(im)
    d.rounded_rectangle((1, 1, 14, 14), radius=2, fill=M + (255,))
    d.ellipse((4, 10, 7, 13), fill=W + (255,))
    d.rectangle((6, 3, 7, 11), fill=W + (255,))
    d.polygon([(7, 3), (11, 5), (11, 7), (7, 5)], fill=W + (255,))
    icons.append(im)
    # 3 VIDEO: blue tile with a play button
    im = canvas(); d = ImageDraw.Draw(im)
    d.rounded_rectangle((1, 2, 14, 13), radius=2, fill=B + (255,))
    d.polygon([(6, 5), (6, 10), (11, 7)], fill=W + (255,))
    icons.append(im)
    # 4 GAME: gamepad
    im = canvas(); d = ImageDraw.Draw(im)
    d.rounded_rectangle((1, 5, 14, 11), radius=3, fill=G + (255,),
                        outline=K + (255,))
    d.rectangle((3, 6, 5, 10), fill=K + (255,))
    d.rectangle((2, 7, 6, 9), fill=K + (255,))
    d.ellipse((9, 6, 12, 9), fill=R + (255,))
    icons.append(im)
    # 5 QUIT: power symbol
    im = canvas(); d = ImageDraw.Draw(im)
    d.ellipse((1, 1, 14, 14), fill=R + (255,))
    d.ellipse((3, 3, 12, 12), fill=T)
    d.rectangle((7, 0, 8, 7), fill=W + (255,))
    icons.append(im)

    out = bytearray()
    for im in icons:
        arr = np.asarray(im).reshape(-1, 4)
        idx = to_index(arr[:, :3])
        idx[arr[:, 3] < 128] = 0xFF
        out += idx.tobytes()
    write("icons.bin", bytes(out))


if __name__ == "__main__":
    make_palette_and_consts()
    make_font()
    make_text()
    make_music()
    make_picture()
    make_video()
    make_icons()
